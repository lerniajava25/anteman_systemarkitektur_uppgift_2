package uppgift_2;

/**
 * The interface Snowmobile.
 */
public interface Snowmobile {
    /**
     * Gets motor.
     *
     * @return the motor
     */
    Motor getMotor();

    /**
     * Gets track length.
     *
     * @return the track length
     */
    int getTrackLength();

    /**
     * Gets track width.
     *
     * @return the track width
     */
    int getTrackWidth();

    /**
     * Is for work boolean.
     *
     * @return the boolean
     */
    boolean isForWork();
}
