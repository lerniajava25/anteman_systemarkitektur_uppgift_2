package uppgift_2;

/**
 * The interface Motor.
 */
public interface Motor {
    /**
     * Gets horse power.
     *
     * @return the horse power
     */
    int getHorsePower();

    /**
     * Gets cylinder count.
     *
     * @return the cylinder count
     */
    int getCylinderCount();

    /**
     * Is electric boolean.
     *
     * @return the boolean
     */
    boolean isElectric();
}
